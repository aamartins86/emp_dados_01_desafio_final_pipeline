"""Criação e reconciliação transacional do modelo estrela da camada Ouro."""

from datetime import date

import psycopg
from psycopg import sql

from src.analytics.calendar import CALENDAR_START, build_calendar
from src.analytics.models import GoldMetrics


GOLD_TABLES = {
    "dim_calendario",
    "dim_indicador",
    "fct_indicadores_economicos",
}

SILVER_REQUIRED_COLUMNS = {
    "tb_dim_indicador": {
        "codigo_sgs",
        "nome_indicador",
        "unidade_medida",
        "periodicidade",
        "ativo",
    },
    "tb_indicadores_economicos": {
        "codigo_sgs",
        "data_referencia",
        "valor",
    },
}


def validate_silver_contract(conn: psycopg.Connection, silver_schema: str) -> None:
    """Interrompe a carga quando a origem não atende ao contrato da SPEC 003."""
    rows = conn.execute(
        """
        SELECT table_name, column_name
        FROM information_schema.columns
        WHERE table_schema = %s
          AND table_name IN ('tb_dim_indicador', 'tb_indicadores_economicos')
        """,
        (silver_schema,),
    ).fetchall()
    actual: dict[str, set[str]] = {}
    for table_name, column_name in rows:
        actual.setdefault(table_name, set()).add(column_name)

    problems = []
    for table_name, required in SILVER_REQUIRED_COLUMNS.items():
        missing = required - actual.get(table_name, set())
        if missing:
            problems.append(f"{table_name}: faltam {sorted(missing)}")
    if problems:
        raise RuntimeError("Contrato Prata incompatível: " + "; ".join(problems))


def initialize_gold_schema(conn: psycopg.Connection, gold_schema: str) -> None:
    """Cria exclusivamente as duas dimensões e a fato previstas na SPEC."""
    schema = sql.Identifier(gold_schema)
    with conn.transaction():
        conn.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(schema))
        conn.execute(
            sql.SQL(
                """
                CREATE TABLE IF NOT EXISTS {}.dim_calendario (
                    id_data INTEGER PRIMARY KEY,
                    data DATE NOT NULL UNIQUE,
                    dia SMALLINT NOT NULL,
                    mes SMALLINT NOT NULL,
                    nome_mes VARCHAR(20) NOT NULL,
                    trimestre SMALLINT NOT NULL,
                    ano INTEGER NOT NULL,
                    ano_mes INTEGER NOT NULL,
                    mes_ano VARCHAR(20) NOT NULL,
                    dia_semana SMALLINT NOT NULL,
                    nome_dia_semana VARCHAR(20) NOT NULL,
                    fim_de_semana BOOLEAN NOT NULL
                )
                """
            ).format(schema)
        )
        conn.execute(
            sql.SQL(
                """
                CREATE TABLE IF NOT EXISTS {}.dim_indicador (
                    id_indicador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    codigo_sgs INTEGER NOT NULL UNIQUE,
                    nome_indicador VARCHAR(150) NOT NULL,
                    unidade_medida VARCHAR(50) NOT NULL,
                    periodicidade VARCHAR(20) NOT NULL,
                    ativo BOOLEAN NOT NULL
                )
                """
            ).format(schema)
        )
        conn.execute(
            sql.SQL(
                """
                CREATE TABLE IF NOT EXISTS {}.fct_indicadores_economicos (
                    id_fato BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_indicador INTEGER NOT NULL
                        REFERENCES {}.dim_indicador(id_indicador),
                    id_data INTEGER NOT NULL
                        REFERENCES {}.dim_calendario(id_data),
                    valor_indicador NUMERIC(20,8) NOT NULL,
                    CONSTRAINT uq_fct_indicador_data UNIQUE (id_indicador, id_data)
                )
                """
            ).format(schema, schema, schema)
        )
        conn.execute(
            sql.SQL(
                "CREATE INDEX IF NOT EXISTS idx_fct_indicadores_id_data "
                "ON {}.fct_indicadores_economicos (id_data)"
            ).format(schema)
        )


def validate_gold_scope(conn: psycopg.Connection, gold_schema: str) -> None:
    """Garante que o schema contenha somente as três tabelas analíticas."""
    rows = conn.execute(
        """
        SELECT table_name
        FROM information_schema.tables
        WHERE table_schema = %s AND table_type = 'BASE TABLE'
        """,
        (gold_schema,),
    ).fetchall()
    actual = {row[0] for row in rows}
    if actual != GOLD_TABLES:
        missing = sorted(GOLD_TABLES - actual)
        unexpected = sorted(actual - GOLD_TABLES)
        raise RuntimeError(
            f"Schema Ouro fora do contrato; ausentes={missing}, não permitidas={unexpected}"
        )


def _calendar_end(
    conn: psycopg.Connection,
    silver_schema: str,
    current_date: date,
) -> date:
    minimum, maximum = conn.execute(
        sql.SQL(
            "SELECT MIN(data_referencia), MAX(data_referencia) "
            "FROM {}.tb_indicadores_economicos"
        ).format(sql.Identifier(silver_schema))
    ).fetchone()
    if minimum is not None and minimum < CALENDAR_START:
        raise RuntimeError("A Prata contém data anterior ao início permitido: 01/01/2023")
    return max(current_date, maximum or CALENDAR_START)


def _load_calendar(
    conn: psycopg.Connection,
    silver_schema: str,
    gold_schema: str,
    current_date: date,
) -> int:
    rows = build_calendar(
        CALENDAR_START,
        _calendar_end(conn, silver_schema, current_date),
    )
    query = sql.SQL(
        """
        INSERT INTO {}.dim_calendario (
            id_data, data, dia, mes, nome_mes, trimestre, ano, ano_mes,
            mes_ano, dia_semana, nome_dia_semana, fim_de_semana
        ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (data) DO UPDATE SET
            dia = EXCLUDED.dia,
            mes = EXCLUDED.mes,
            nome_mes = EXCLUDED.nome_mes,
            trimestre = EXCLUDED.trimestre,
            ano = EXCLUDED.ano,
            ano_mes = EXCLUDED.ano_mes,
            mes_ano = EXCLUDED.mes_ano,
            dia_semana = EXCLUDED.dia_semana,
            nome_dia_semana = EXCLUDED.nome_dia_semana,
            fim_de_semana = EXCLUDED.fim_de_semana
        """
    ).format(sql.Identifier(gold_schema))
    with conn.cursor() as cursor:
        cursor.executemany(query, [item.as_tuple() for item in rows])
    return len(rows)


def _load_indicators(
    conn: psycopg.Connection,
    silver_schema: str,
    gold_schema: str,
) -> int:
    query = sql.SQL(
        """
        INSERT INTO {}.dim_indicador (
            codigo_sgs, nome_indicador, unidade_medida, periodicidade, ativo
        )
        SELECT codigo_sgs, nome_indicador, unidade_medida, periodicidade, ativo
        FROM {}.tb_dim_indicador
        ON CONFLICT (codigo_sgs) DO UPDATE SET
            nome_indicador = EXCLUDED.nome_indicador,
            unidade_medida = EXCLUDED.unidade_medida,
            periodicidade = EXCLUDED.periodicidade,
            ativo = EXCLUDED.ativo
        """
    ).format(sql.Identifier(gold_schema), sql.Identifier(silver_schema))
    conn.execute(query)
    return conn.execute(
        sql.SQL("SELECT COUNT(*) FROM {}.dim_indicador").format(
            sql.Identifier(gold_schema)
        )
    ).fetchone()[0]


def _fact_metrics(
    conn: psycopg.Connection,
    silver_schema: str,
    gold_schema: str,
) -> tuple[int, int, int]:
    row = conn.execute(
        sql.SQL(
            """
            SELECT
                COUNT(*) AS total,
                COUNT(*) FILTER (WHERE fato.id_fato IS NULL) AS inserir,
                COUNT(*) FILTER (
                    WHERE fato.id_fato IS NOT NULL
                      AND fato.valor_indicador IS DISTINCT FROM origem.valor
                ) AS atualizar
            FROM {}.tb_indicadores_economicos origem
            JOIN {}.dim_indicador indicador
              ON indicador.codigo_sgs = origem.codigo_sgs
            LEFT JOIN {}.fct_indicadores_economicos fato
              ON fato.id_indicador = indicador.id_indicador
             AND fato.id_data = (
                 EXTRACT(YEAR FROM origem.data_referencia)::INTEGER * 10000
                 + EXTRACT(MONTH FROM origem.data_referencia)::INTEGER * 100
                 + EXTRACT(DAY FROM origem.data_referencia)::INTEGER
             )
            """
        ).format(
            sql.Identifier(silver_schema),
            sql.Identifier(gold_schema),
            sql.Identifier(gold_schema),
        )
    ).fetchone()
    return row[0], row[1], row[2]


def _load_facts(
    conn: psycopg.Connection,
    silver_schema: str,
    gold_schema: str,
) -> int:
    silver = sql.Identifier(silver_schema)
    gold = sql.Identifier(gold_schema)
    conn.execute(
        sql.SQL(
            """
            INSERT INTO {}.fct_indicadores_economicos AS fato (
                id_indicador, id_data, valor_indicador
            )
            SELECT
                indicador.id_indicador,
                calendario.id_data,
                origem.valor
            FROM {}.tb_indicadores_economicos origem
            JOIN {}.dim_indicador indicador
              ON indicador.codigo_sgs = origem.codigo_sgs
            JOIN {}.dim_calendario calendario
              ON calendario.data = origem.data_referencia
            ON CONFLICT (id_indicador, id_data) DO UPDATE SET
                valor_indicador = EXCLUDED.valor_indicador
            WHERE fato.valor_indicador IS DISTINCT FROM EXCLUDED.valor_indicador
            """
        ).format(gold, silver, gold, gold)
    )

    deleted = conn.execute(
        sql.SQL(
            """
            DELETE FROM {}.fct_indicadores_economicos fato
            WHERE NOT EXISTS (
                SELECT 1
                FROM {}.tb_indicadores_economicos origem
                JOIN {}.dim_indicador indicador
                  ON indicador.codigo_sgs = origem.codigo_sgs
                JOIN {}.dim_calendario calendario
                  ON calendario.data = origem.data_referencia
                WHERE indicador.id_indicador = fato.id_indicador
                  AND calendario.id_data = fato.id_data
            )
            """
        ).format(gold, silver, gold, gold)
    )
    return deleted.rowcount


def reconcile_gold(
    conn: psycopg.Connection,
    silver_schema: str,
    gold_schema: str,
    current_date: date,
) -> GoldMetrics:
    """Reconcilia Prata e Ouro por UPSERT, preservando todas as chaves existentes."""
    validate_silver_contract(conn, silver_schema)
    initialize_gold_schema(conn, gold_schema)
    validate_gold_scope(conn, gold_schema)

    metrics = GoldMetrics()
    with conn.transaction():
        metrics.calendar_rows = _load_calendar(
            conn, silver_schema, gold_schema, current_date
        )
        metrics.indicator_rows = _load_indicators(conn, silver_schema, gold_schema)
        metrics.source_rows, metrics.inserted, metrics.updated = _fact_metrics(
            conn, silver_schema, gold_schema
        )
        metrics.unchanged = metrics.source_rows - metrics.inserted - metrics.updated
        metrics.removed = _load_facts(conn, silver_schema, gold_schema)
    return metrics
